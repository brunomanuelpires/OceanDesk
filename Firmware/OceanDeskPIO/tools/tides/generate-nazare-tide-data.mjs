#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { constituents as constituentModels } from "@neaps/tide-predictor";

const stationId = "ticon/nazaretg-naz-prt-cmems";
const expectedConstituentCount = 50;
const majorConstituentNames = ["M2", "N2", "S2", "K2", "K1", "P1", "O1", "Q1"];
const ihoFundamentals = new Set(["Mm", "Mf", "O1", "K1", "J1", "M1", "M2", "K2", "M3", "L2"]);
const inputPath = resolve("tools/tides/generated/portugal-stations.json");
const headerPath = resolve("src/tides/data/NazareTideData.h");
const sourcePath = resolve("src/tides/data/NazareTideData.cpp");

function formatFloat(value, digits) {
  return `${value.toFixed(digits)}f`;
}

function resolveModel(name) {
  const model = constituentModels[name];
  if (!model || !Array.isArray(model.coefficients) || model.coefficients.length !== 7) {
    throw new Error(`No complete Neaps Doodson definition for constituent ${name}`);
  }
  if (!model.coefficients.every(Number.isInteger)) {
    throw new Error(`Non-integer Doodson coefficient for constituent ${name}`);
  }
  return model;
}

function orderConstituents(harmonics) {
  const byName = new Map(harmonics.map((harmonic) => [harmonic.name, harmonic]));
  if (byName.size !== harmonics.length) throw new Error("Nazaré contains duplicate constituent names");

  const major = majorConstituentNames.map((name) => {
    const harmonic = byName.get(name);
    if (!harmonic) throw new Error(`Nazaré is missing major constituent ${name}`);
    return harmonic;
  });
  const majorNames = new Set(majorConstituentNames);
  return [...major, ...harmonics.filter(({ name }) => !majorNames.has(name))];
}

function resolveNodalTerms(model, factor = 1, terms = []) {
  if (ihoFundamentals.has(model.name)) {
    terms.push({ fundamental: model.name, factor });
    return terms;
  }
  for (const member of model.members) {
    resolveNodalTerms(member.constituent, factor * member.factor, terms);
  }
  return terms;
}

function renderNodalTerms(model) {
  const terms = resolveNodalTerms(model);
  if (terms.length > 2) {
    throw new Error(`More than two flattened IHO nodal terms for constituent ${model.name}`);
  }
  const rendered = terms.map(({ fundamental, factor }) =>
    `{TideNodalFundamental::${fundamental}, ${formatFloat(factor, 2)}}`);
  while (rendered.length < 2) rendered.push("{TideNodalFundamental::None, 0.00f}");
  return `{${rendered.join(", ")}}, ${terms.length}`;
}

function renderHeader() {
  return `// Generated by tools/tides/generate-nazare-tide-data.mjs. Do not edit manually.
#pragma once

#include "tides/TideEngine.h"

namespace TideDevelopmentData
{
// Development-only station data licensed CC BY-NC 4.0.
extern const TideHarmonicStation nazare;
}
`;
}

function renderSource(station) {
  const ordered = orderConstituents(station.harmonicConstituents);
  const rows = ordered.map((harmonic) => {
    if (!Number.isFinite(harmonic.amplitude) || !Number.isFinite(harmonic.phase)) {
      throw new Error(`Invalid amplitude or phase for constituent ${harmonic.name}`);
    }
    const model = resolveModel(harmonic.name);
    const coefficients = model.coefficients.join(", ");
    const nodalTerms = renderNodalTerms(model);
    const aliasNote = model.name === harmonic.name ? "" : ` (Neaps: ${model.name})`;
    return `    {${formatFloat(harmonic.amplitude, 8)}, ${formatFloat(harmonic.phase, 6)}, {${coefficients}}, ${nodalTerms}}, // ${harmonic.name}${aliasNote}`;
  });

  return `// Generated by tools/tides/generate-nazare-tide-data.mjs. Do not edit manually.
// Source: tools/tides/generated/portugal-stations.json
#include "NazareTideData.h"

namespace
{
// Development-only data. The first eight entries are the historical major-
// constituent baseline used by the host comparison tests.
constexpr TideConstituent constituents[] = {
    // amplitude (m), phase UTC (degrees), Doodson coefficients, IHO nodal terms
${rows.join("\n")}
};

static_assert(sizeof(constituents) / sizeof(constituents[0]) == ${expectedConstituentCount},
              "Nazaré development dataset must contain ${expectedConstituentCount} constituents");
} // namespace

namespace TideDevelopmentData
{
const TideHarmonicStation nazare = {
    "${station.id}",
    "${station.name}",
    "${station.source.name} via Neaps Tide Database",
    "CC BY-NC 4.0",
    constituents,
    sizeof(constituents) / sizeof(constituents[0]),
    true,
};
}
`;
}

async function main() {
  const checkOnly = process.argv.slice(2).includes("--check");
  const dataset = JSON.parse(await readFile(inputPath, "utf8"));
  const station = dataset.stations?.find(({ id }) => id === stationId);
  if (!station) throw new Error(`Station ${stationId} not found in ${inputPath}`);
  if (station.harmonicConstituents?.length !== expectedConstituentCount) {
    throw new Error(`Expected ${expectedConstituentCount} Nazaré constituents, found ${station.harmonicConstituents?.length ?? 0}`);
  }
  if (station.license?.type !== "cc-by-nc-4.0" || station.license?.commercialUse !== false) {
    throw new Error("Nazaré must remain marked as CC BY-NC 4.0 / non-commercial");
  }

  const outputs = [
    [headerPath, renderHeader()],
    [sourcePath, renderSource(station)],
  ];

  if (checkOnly) {
    for (const [path, expected] of outputs) {
      const actual = await readFile(path, "utf8");
      if (actual !== expected) throw new Error(`${path} is stale; regenerate Nazaré tide data`);
    }
    console.log("Nazaré generated tide data is current (50 constituents).");
    return;
  }

  await Promise.all(outputs.map(([path, content]) => writeFile(path, content, "utf8")));
  console.log("Generated Nazaré tide data with 50 constituents.");
}

main().catch((error) => {
  console.error(`tides:generate-nazare: ${error.message}`);
  process.exitCode = 1;
});
