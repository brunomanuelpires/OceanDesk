#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { constituents as constituentModels } from "@neaps/tide-predictor";

const stationId = "ticon/cascais-209-prt-uhslc_fd";
const expectedConstituentCount = 50;
const majorNames = ["M2", "N2", "S2", "K2", "K1", "P1", "O1", "Q1"];
const fundamentals = new Set(["Mm", "Mf", "O1", "K1", "J1", "M1", "M2", "K2", "M3", "L2"]);
const inputPath = resolve("tools/tides/generated/portugal-stations.json");
const headerPath = resolve("src/tides/data/CascaisTideData.h");
const sourcePath = resolve("src/tides/data/CascaisTideData.cpp");
const float = (value, digits) => `${value.toFixed(digits)}f`;

function modelFor(name) {
  const model = constituentModels[name];
  if (!model || !Array.isArray(model.coefficients) || model.coefficients.length !== 7 ||
      !model.coefficients.every(Number.isInteger)) {
    throw new Error(`No complete Neaps Doodson definition for constituent ${name}`);
  }
  return model;
}

function nodalTerms(model, factor = 1, output = []) {
  if (fundamentals.has(model.name)) return output.concat({ fundamental: model.name, factor });
  return model.members.reduce((terms, member) => nodalTerms(member.constituent, factor * member.factor, terms), output);
}

function renderTerms(model) {
  const terms = nodalTerms(model);
  if (terms.length > 2) throw new Error(`More than two flattened IHO nodal terms for ${model.name}`);
  const values = terms.map(({ fundamental, factor }) =>
    `{TideNodalFundamental::${fundamental}, ${float(factor, 2)}}`);
  while (values.length < 2) values.push("{TideNodalFundamental::None, 0.00f}");
  return `{${values.join(", ")}}, ${terms.length}`;
}

function render(station) {
  const byName = new Map(station.harmonicConstituents.map((harmonic) => [harmonic.name, harmonic]));
  if (byName.size !== station.harmonicConstituents.length) throw new Error("Cascais contains duplicate constituent names");
  const major = majorNames.map((name) => {
    const harmonic = byName.get(name);
    if (!harmonic) throw new Error(`Cascais is missing major constituent ${name}`);
    return harmonic;
  });
  const ordered = [...major, ...station.harmonicConstituents.filter(({ name }) => !majorNames.includes(name))];
  const rows = ordered.map((harmonic) => {
    if (!Number.isFinite(harmonic.amplitude) || !Number.isFinite(harmonic.phase)) throw new Error(`Invalid ${harmonic.name}`);
    const model = modelFor(harmonic.name);
    const alias = model.name === harmonic.name ? "" : ` (Neaps: ${model.name})`;
    return `    {${float(harmonic.amplitude, 8)}, ${float(harmonic.phase, 6)}, {${model.coefficients.join(", ")}}, ${renderTerms(model)}}, // ${harmonic.name}${alias}`;
  });
  const header = `// Generated by tools/tides/generate-cascais-tide-data.mjs. Do not edit manually.\n#pragma once\n\n#include "tides/TideEngine.h"\n\nnamespace TideDevelopmentData\n{\n// Development-only station data licensed CC BY 4.0.\nextern const TideHarmonicStation cascais;\n}\n`;
  const source = `// Generated by tools/tides/generate-cascais-tide-data.mjs. Do not edit manually.\n// Source: tools/tides/generated/portugal-stations.json\n#include "CascaisTideData.h"\n\nnamespace\n{\n// The first eight entries are the historical major-constituent baseline.\nconstexpr TideConstituent constituents[] = {\n    // amplitude (m), phase UTC (degrees), Doodson coefficients, IHO nodal terms\n${rows.join("\n")}\n};\n\nstatic_assert(sizeof(constituents) / sizeof(constituents[0]) == ${expectedConstituentCount},\n              "Cascais development dataset must contain ${expectedConstituentCount} constituents");\n} // namespace\n\nnamespace TideDevelopmentData\n{\nconst TideHarmonicStation cascais = {\n    "${station.id}",\n    "${station.name}",\n    "${station.source.name} via Neaps Tide Database",\n    "CC BY 4.0",\n    constituents,\n    sizeof(constituents) / sizeof(constituents[0]),\n    true,\n};\n}\n`;
  return [[headerPath, header], [sourcePath, source]];
}

const checkOnly = process.argv.slice(2).includes("--check");
const dataset = JSON.parse(await readFile(inputPath, "utf8"));
const station = dataset.stations?.find(({ id }) => id === stationId);
if (!station || station.type !== "reference" || station.harmonicConstituents?.length !== expectedConstituentCount ||
    station.license?.type !== "cc-by-4.0" || station.license?.commercialUse !== true) {
  throw new Error("Cascais must be a 50-constituent commercial-use CC BY 4.0 reference station");
}
for (const [path, content] of render(station)) {
  if (checkOnly) {
    if (await readFile(path, "utf8") !== content) throw new Error(`${path} is stale; regenerate Cascais tide data`);
  } else await writeFile(path, content, "utf8");
}
console.log(checkOnly ? "Cascais generated tide data is current (50 constituents)." : "Generated Cascais tide data with 50 constituents.");
