#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { constituents as constituentModels } from "@neaps/tide-predictor";

const inputPath = resolve("tools/tides/generated/fes2022-portugal-harmonics.json");
const ihoFundamentals = new Set(["Mm", "Mf", "O1", "K1", "J1", "M1", "M2", "K2", "M3", "L2"]);

function formatFloat(value, digits) { return `${value.toFixed(digits)}f`; }

function resolveNodalTerms(model, factor = 1, terms = []) {
  if (ihoFundamentals.has(model.name)) return [...terms, { fundamental: model.name, factor }];
  return model.members.reduce((result, member) =>
    resolveNodalTerms(member.constituent, factor * member.factor, result), terms);
}

function renderRow([name, modelName, fileName, amplitudeCm, phase]) {
  const model = constituentModels[modelName];
  if (!model?.coefficients || model.coefficients.length !== 7) {
    throw new Error(`No complete Doodson definition for ${name}`);
  }
  const terms = resolveNodalTerms(model);
  if (terms.length > 2) throw new Error(`${name} expands to more than two nodal terms`);
  const renderedTerms = terms.map(({ fundamental, factor }) =>
    `{TideNodalFundamental::${fundamental}, ${formatFloat(factor, 2)}}`);
  while (renderedTerms.length < 2) renderedTerms.push("{TideNodalFundamental::None, 0.00f}");
  const sourceNote = modelName === name ? "" : ` (model: ${modelName})`;
  return `    {${formatFloat(amplitudeCm / 100, 8)}, ${formatFloat(phase, 6)}, {${model.coefficients.join(", ")}}, {${renderedTerms.join(", ")}}, ${terms.length}}, // ${name}${sourceNote}; ${fileName}_fes2022.nc.xz`;
}

function renderHeader(station, symbol) {
  return `// Generated by tools/tides/generate-fes2022-tide-data.mjs. Do not edit manually.\n#pragma once\n\n#include "tides/TideEngine.h"\n\nnamespace TideDevelopmentData\n{\nextern const TideHarmonicStation ${symbol};\n}\n`;
}

function renderSource(station, symbol, source) {
  const rows = station.harmonics.map(renderRow).join("\n");
  return `// Generated by tools/tides/generate-fes2022-tide-data.mjs. Do not edit manually.\n// Source: tools/tides/generated/fes2022-portugal-harmonics.json\n// ${source.attribution}\n#include "${symbol[0].toUpperCase()}${symbol.slice(1)}TideData.h"\n\nnamespace\n{\nconstexpr TideConstituent constituents[] = {\n    // amplitude (m), phase UTC (degrees), Doodson coefficients, IHO nodal terms\n${rows}\n};\n\nstatic_assert(sizeof(constituents) / sizeof(constituents[0]) == ${station.harmonics.length},\n              "FES2022 ${station.name} dataset must contain ${station.harmonics.length} constituents");\n} // namespace\n\nnamespace TideDevelopmentData\n{\nconst TideHarmonicStation ${symbol} = {\n    "${station.id}",\n    "${station.name}",\n    "FES2022b ocean tide extrapolated via AVISO",\n    "AVISO Licence",\n    constituents,\n    sizeof(constituents) / sizeof(constituents[0]),\n    true,\n};\n}\n`;
}

async function main() {
  const checkOnly = process.argv.includes("--check");
  const dataset = JSON.parse(await readFile(inputPath, "utf8"));
  if (dataset.schemaVersion !== 1 || dataset.source?.version !== "FES2022b") throw new Error("Unsupported FES dataset");
  for (const station of dataset.stations) {
    const symbol = station.name.toLowerCase();
    if (!Array.isArray(station.harmonics) || station.harmonics.length !== 34) {
      throw new Error(`${station.name} must contain the 34 FES2022 constituents`);
    }
    const title = `${symbol[0].toUpperCase()}${symbol.slice(1)}TideData`;
    const outputs = [
      [resolve(`src/tides/data/${title}.h`), renderHeader(station, symbol)],
      [resolve(`src/tides/data/${title}.cpp`), renderSource(station, symbol, dataset.source)],
    ];
    for (const [path, content] of outputs) {
      if (checkOnly) {
        if (await readFile(path, "utf8") !== content) throw new Error(`${path} is stale; regenerate FES2022 tide data`);
      } else {
        await writeFile(path, content, "utf8");
      }
    }
  }
  console.log(checkOnly ? "FES2022 tide data is current (34 constituents per station)." : "Generated FES2022 tide data for Nazaré and Peniche.");
}

main().catch((error) => { console.error(`tides:generate-fes2022: ${error.message}`); process.exitCode = 1; });
