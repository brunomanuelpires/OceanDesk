#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { catalogAreaCppNames, validateBeachCatalog } from "./beach-catalog-lib.mjs";

const catalogPath = resolve("tools/tides/portugal-beach-catalog.json");
const stationsPath = resolve("tools/tides/generated/portugal-stations.json");
const outputPath = resolve("src/locations/PortugalBeachCatalogData.inc");

const cppString = (value) => JSON.stringify(value ?? "");

function render({ tideModels, beaches }) {
  const modelRows = tideModels.map((model) =>
    `    {${cppString(model.id)}, ${cppString(model.stationId)}, ${cppString(model.displayName)}, ${catalogAreaCppNames[model.area]}, ${model.latitude}, ${model.longitude}, ${cppString(model.timezone)}, true},`);
  const beachRows = beaches.map((beach) =>
    `    {${cppString(beach.id)}, ${cppString(beach.displayName)}, ${cppString(beach.shortName)}, ${cppString(beach.region)}, ${cppString(beach.country)}, ${catalogAreaCppNames[beach.area]}, ${beach.latitude}, ${beach.longitude}, ${cppString(beach.tideModelId)}, ${cppString(beach.timezone)}},`);

  return `// Generated by tools/tides/generate-beach-catalog.mjs. Do not edit manually.
constexpr TideModel tideModels[] = {
${modelRows.join("\n")}
};

constexpr BeachLocation beaches[] = {
${beachRows.join("\n")}
};
`;
}

async function main() {
  const checkOnly = process.argv.slice(2).includes("--check");
  const [catalog, stationDataset] = await Promise.all([
    readFile(catalogPath, "utf8").then(JSON.parse),
    readFile(stationsPath, "utf8").then(JSON.parse),
  ]);
  const validated = validateBeachCatalog(catalog, stationDataset);
  const expected = render(validated);

  if (checkOnly) {
    const actual = await readFile(outputPath, "utf8");
    if (actual !== expected) throw new Error(`${outputPath} is stale; regenerate the beach catalog`);
    console.log(`Beach catalog is current (${validated.beaches.length} beaches, ${validated.tideModels.length} model).`);
    return;
  }

  await writeFile(outputPath, expected, "utf8");
  console.log(`Generated ${validated.beaches.length} beaches using ${validated.tideModels.length} tide model.`);
}

main().catch((error) => {
  console.error(`tides:generate-beach-catalog: ${error.message}`);
  process.exitCode = 1;
});
